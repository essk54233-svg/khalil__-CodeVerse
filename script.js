function updateGlobalStats() {
  const totalDone = Object.values(progress)
    .reduce((sum, items) => sum + items.length, 0);

  const started = Object.values(progress)
    .filter(items => items.length > 0).length;

  document.getElementById("completedCount").textContent = totalDone;
  document.getElementById("totalDone").textContent = totalDone;
  document.getElementById("startedCourses").textContent = started;
  document.getElementById("totalLessons").textContent = languages.reduce((sum, item) => sum + lessonCountFor(item), 0);
}

function renderProgress() {
  updateGlobalStats();

  const list = document.getElementById("progressList");
  list.innerHTML = "";

  const startedLanguages = languages.filter(language =>
    completedFor(language.id).length > 0
  );

  if (startedLanguages.length === 0) {
    list.innerHTML = `
      <div class="empty-state">
        لم تبدأ أي مسار بعد. اختر لغة من المكتبة وابدأ أول درس.
      </div>`;
    return;
  }

  startedLanguages.forEach(language => {
    const done = completedFor(language.id).length;
    const percent = Math.round(done / lessonCountFor(language) * 100);

    const row = document.createElement("div");
    row.className = "progress-row";

    const title = document.createElement("div");
    const name = document.createElement("strong");
    name.textContent = language.name;

    const detail = document.createElement("small");
    detail.textContent = `${done} من ${lessonCountFor(language)} درساً`;

    title.append(name,detail);

    const bar = document.createElement("div");
    bar.className = "progress-track";

    const fill = document.createElement("span");
    fill.style.width = percent + "%";
    bar.appendChild(fill);

    const percentage = document.createElement("b");
    percentage.textContent = percent + "%";

    row.append(title,bar,percentage);
    row.addEventListener("click", () => openCourse(language.id));

    list.appendChild(row);
  });
}

