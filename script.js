function createLanguageCard(language) {
  const card = document.createElement("article");
  card.className = "language-card";
  card.tabIndex = 0;

  const top = document.createElement("div");
  top.className = "language-card-top";

  const iconBox = document.createElement("div");
  iconBox.className = "language-icon";

  const img = document.createElement("img");
  img.src = logoUrl(language.icon);
  img.alt = language.name;
  img.onerror = () => {
    iconBox.innerHTML = `<span class="icon-fallback">${language.name.slice(0,2)}</span>`;
  };

  iconBox.appendChild(img);

  const level = document.createElement("span");
  level.className = "language-level";
  level.textContent = language.level;

  top.append(iconBox, level);

  const name = document.createElement("h3");
  name.textContent = language.name;

  const description = document.createElement("p");
  description.textContent = language.description;

  const bottom = document.createElement("div");
  bottom.className = "card-bottom";

  const count = document.createElement("span");
  count.textContent = "6 دروس تأسيسية";

  const action = document.createElement("b");
  action.textContent = "ابدأ التعلم ←";

  bottom.append(count, action);
  card.append(top, name, description, bottom);

  card.addEventListener("click", () => openCourse(language.id));
  card.addEventListener("keydown", event => {
    if (event.key === "Enter") openCourse(language.id);
  });

  return card;
}

