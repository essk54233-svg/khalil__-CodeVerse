function openCourse(languageId) {
  currentLanguage = languages.find(item => item.id === languageId);

  if (!currentLanguage) return;

  currentLessonIndex = 0;

  const logo = document.getElementById("courseLogo");
  logo.innerHTML = "";

  const img = document.createElement("img");
  img.src = logoUrl(currentLanguage.icon);
  img.alt = currentLanguage.name;
  img.onerror = () => {
    logo.textContent = currentLanguage.name.slice(0,2);
  };

  logo.appendChild(img);

  document.getElementById("courseName").textContent = currentLanguage.name;
  document.getElementById("courseDescription").textContent =
    currentLanguage.description;

  document.getElementById("lessonTotal").textContent = lessonCountFor(currentLanguage) + " درساً";

  renderLessonList();
  renderLesson();

  showView("course");
}

function renderLessonList() {
  lessonList.innerHTML = "";
  const lessons = buildLessons(currentLanguage);

  lessons.forEach((lesson, index) => {
    const button = document.createElement("button");
    button.className = "lesson-item";

    if (index === currentLessonIndex) button.classList.add("active");
    if (isCompleted(currentLanguage.id, index)) button.classList.add("done");

    const number = document.createElement("span");
    number.className = "lesson-number";
    number.textContent = isCompleted(currentLanguage.id,index) ? "✓" : index + 1;

    const title = document.createElement("span");
    title.textContent = lesson.title;

    button.append(number, title);

    button.addEventListener("click", () => {
      currentLessonIndex = index;
      renderLessonList();
      renderLesson();
    });

    lessonList.appendChild(button);
  });

  updateCourseProgress();
}

/* ---------- أدوات بناء الدرس ---------- */

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function section(title) {
  const box = el("section", "lesson-section");
  box.appendChild(el("h3", "", title));
  return box;
}

function bulletList(items, className) {
  const list = el("ul", className || "");
  items.forEach(item => list.appendChild(el("li", "", item)));
  return list;
}

function shuffle(items) {
  const copy = items.slice();
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

/* ---------- تشغيل الكود داخل المتصفح (JavaScript و HTML و CSS) ---------- */

const RUNNABLE = { javascript: "js", html: "html", css: "css" };

const CSS_SAMPLE_PAGE =
  '<h1>عنوان تجريبي</h1><p>فقرة نصية للتجربة.</p>' +
  '<div class="container grid"><div class="card">1</div><div class="card">2</div><div class="card">3</div></div>' +
  '<br><button>زر</button>';

let jsRunnerListener = null;

function runJavaScript(code, output) {
  output.textContent = "جارٍ التشغيل...";

  const safeCode = JSON.stringify(code).replace(/<\//g, "<\\/");
  const doc =
    "<script>" +
    "const out=[];" +
    "const fmt=v=>{try{return typeof v==='object'?JSON.stringify(v):String(v)}catch(e){return String(v)}};" +
    "console.log=(...a)=>out.push(a.map(fmt).join(' '));" +
    "try{new Function(" + safeCode + ")();}catch(e){out.push('خطأ: '+e.message);}" +
    "parent.postMessage({codeverse:true,out:out},'*');" +
    "<\/script>";

  const frame = document.createElement("iframe");
  frame.setAttribute("sandbox", "allow-scripts");
  frame.style.display = "none";

  if (jsRunnerListener) window.removeEventListener("message", jsRunnerListener);

  const timer = setTimeout(() => {
    output.textContent = "انتهت مهلة التشغيل. تأكد أن الكود لا يحتوي حلقة لا نهائية.";
    frame.remove();
  }, 3000);

  jsRunnerListener = event => {
    if (event.source !== frame.contentWindow) return;
    if (!event.data || event.data.codeverse !== true) return;

    clearTimeout(timer);
    const lines = event.data.out || [];
    output.textContent = lines.length ? lines.join("\n") : "(لا توجد مخرجات. استخدم console.log لعرض النتيجة)";
    frame.remove();
  };

  window.addEventListener("message", jsRunnerListener);
  frame.srcdoc = doc;
  document.body.appendChild(frame);
}

function previewHtml(code, frame, isCss) {
  let doc;

  if (isCss) {
    doc = '<meta charset="UTF-8"><style>' + code + "</style>" +
          '<body dir="rtl" style="font-family:sans-serif;padding:14px">' + CSS_SAMPLE_PAGE + "</body>";
  } else if (/^\s*<!doctype/i.test(code)) {
    doc = code;
  } else {
    doc = '<meta charset="UTF-8"><body dir="rtl" style="font-family:sans-serif;padding:14px">' + code + "</body>";
  }

  frame.srcdoc = doc;
}

/* ---------- عرض الدرس ---------- */

function renderLesson() {
  const lessons = buildLessons(currentLanguage);
  const lesson = lessons[currentLessonIndex];
  const topic = lesson.topic;

  lessonContent.innerHTML = "";

  lessonContent.append(
    el("span", "lesson-tag", `الدرس ${currentLessonIndex + 1} من ${lessons.length}`),
    el("h2", "", lesson.title),
    el("p", "lesson-intro", topic.intro)
  );

  /* ماذا ستتعلم */
  if (topic.goals && topic.goals.length) {
    const goals = el("div", "goals-box");
    goals.appendChild(el("strong", "", "ماذا ستتعلم في هذا الدرس؟"));
    goals.appendChild(bulletList(topic.goals));
    lessonContent.appendChild(goals);
  }

  /* الفكرة ببساطة */
  const idea = section("الفكرة ببساطة");
  topic.concept.forEach(paragraph => idea.appendChild(el("p", "", paragraph)));
  if (topic.analogy) idea.appendChild(el("div", "lesson-analogy", "💡 تشبيه: " + topic.analogy));
  lessonContent.appendChild(idea);

  /* مثال عملي (أو توضيح للدروس النظرية) */
  if (lesson.code) {
  const example = section(lesson.theory ? "توضيح" : "مثال عملي");

  const codeWrap = el("div", "code-wrap");
  const copyButton = el("button", "copy-btn", "نسخ");
  copyButton.type = "button";
  const code = el("pre", "lesson-code");
  code.textContent = lesson.code;

  copyButton.addEventListener("click", () => {
    if (navigator.clipboard) {
      navigator.clipboard.writeText(lesson.code).then(() => {
        copyButton.textContent = "تم النسخ ✓";
        setTimeout(() => { copyButton.textContent = "نسخ"; }, 1500);
      }).catch(() => {});
    }
  });

  codeWrap.append(copyButton, code);
  example.appendChild(codeWrap);

  if (lesson.output) {
    const outputBox = el("div", "lesson-output");
    outputBox.appendChild(el("span", "output-label", "المخرجات المتوقعة"));
    outputBox.appendChild(el("pre", "", lesson.output));
    example.appendChild(outputBox);
  }

  if (lesson.note) {
    const explain = el("div", "lesson-note");
    explain.appendChild(el("strong", "", "شرح المثال: "));
    explain.appendChild(document.createTextNode(lesson.note));
    example.appendChild(explain);
  }

  lessonContent.appendChild(example);
  }

  /* أخطاء شائعة */
  const mistakes = section(lesson.theory ? "أفكار خاطئة شائعة" : "أخطاء شائعة يقع فيها المبتدئون");
  mistakes.appendChild(bulletList(topic.mistakes));
  lessonContent.appendChild(mistakes);

  /* جرّب بنفسك (للدروس العملية) أو فكّر (للنظرية) */
  const practice = section(lesson.theory ? "فكّر وطبّق" : "جرّب بنفسك");
  practice.appendChild(el("p", "practice-task", "🎯 المهمة: " + topic.task));
  if (lesson.theory) {
    const tip = el("div", "hint-box", "💬 تلميح: " + topic.hint);
    practice.appendChild(tip);
  } else {

  const editor = el("textarea", "code-editor");
  editor.value = lesson.code;
  editor.spellcheck = false;
  editor.setAttribute("dir", "ltr");
  editor.rows = Math.min(Math.max(lesson.code.split("\n").length + 1, 5), 16);

  editor.addEventListener("keydown", event => {
    if (event.key === "Tab") {
      event.preventDefault();
      const start = editor.selectionStart;
      const end = editor.selectionEnd;
      editor.value = editor.value.slice(0, start) + "  " + editor.value.slice(end);
      editor.selectionStart = editor.selectionEnd = start + 2;
    }
  });

  const actions = el("div", "editor-actions");
  const kind = RUNNABLE[currentLanguage.id];

  let runButton = null;
  if (kind) {
    runButton = el("button", "run-btn", "▶ تشغيل");
    runButton.type = "button";
    actions.appendChild(runButton);
  }

  const resetButton = el("button", "ghost-btn", "إعادة الكود الأصلي");
  resetButton.type = "button";
  resetButton.addEventListener("click", () => { editor.value = lesson.code; });

  const hintButton = el("button", "ghost-btn", "💬 تلميح");
  hintButton.type = "button";

  actions.append(resetButton, hintButton);

  const hintBox = el("div", "hint-box hidden", topic.hint);
  hintButton.addEventListener("click", () => hintBox.classList.toggle("hidden"));

  practice.append(editor, actions, hintBox);

  if (kind === "js") {
    const out = el("pre", "run-output", "اضغط «تشغيل» لرؤية النتيجة هنا.");
    runButton.addEventListener("click", () => runJavaScript(editor.value, out));
    practice.appendChild(out);
  } else if (kind === "html" || kind === "css") {
    const frame = document.createElement("iframe");
    frame.className = "preview-frame";
    frame.setAttribute("sandbox", "");
    frame.title = "معاينة";
    runButton.addEventListener("click", () => previewHtml(editor.value, frame, kind === "css"));
    previewHtml(editor.value, frame, kind === "css");
    practice.appendChild(frame);
  } else {
    practice.appendChild(el("p", "run-hint",
      "هذه اللغة لا تعمل داخل المتصفح. انسخ الكود وجرّبه على جهازك أو في محرر أونلاين يدعم " + currentLanguage.name + "."));
  }

  }

  lessonContent.appendChild(practice);

  /* ملخص */
  const summary = section("ملخص الدرس");
  summary.appendChild(bulletList(topic.summary, "summary-list"));
  lessonContent.appendChild(summary);

  /* اختبار اختياري */
  if (topic.quiz) {
    const details = el("details", "quiz-details");
    details.appendChild(el("summary", "", "اختبر نفسك (اختياري)"));

    const exercise = el("div", "exercise-box");
    exercise.appendChild(el("p", "", topic.quiz.question));

    const options = el("div", "exercise-options");
    const feedback = el("div", "quiz-feedback");

    shuffle(topic.quiz.options.map((text, index) => ({ text, correct: index === topic.quiz.answer })))
      .forEach(option => {
        const button = el("button", "quiz-option", option.text);
        button.type = "button";
        button.dataset.correct = option.correct ? "1" : "0";

        button.addEventListener("click", () => {
          options.querySelectorAll("button").forEach(item => {
            item.disabled = true;
            if (item.dataset.correct === "1") item.classList.add("correct");
          });

          if (option.correct) {
            feedback.style.color = "var(--green)";
            feedback.textContent = "إجابة صحيحة. " + topic.quiz.explanation;
          } else {
            button.classList.add("wrong");
            feedback.style.color = "#ff9999";
            feedback.textContent = "ليست الإجابة الصحيحة. " + topic.quiz.explanation;
          }
        });

        options.appendChild(button);
      });

    exercise.append(options, feedback);
    details.appendChild(exercise);
    lessonContent.appendChild(details);
  }

  /* التنقل */
  const footer = el("div", "lesson-footer");

  const completeButton = el("button", "complete-btn",
    isCompleted(currentLanguage.id, currentLessonIndex) ? "✓ مكتمل" : "إكمال الدرس");

  completeButton.addEventListener("click", () => {
    markCompleted(currentLanguage.id, currentLessonIndex);
    completeButton.textContent = "✓ مكتمل";
    renderLessonList();
  });

  const nextButton = el("button", "next-btn",
    currentLessonIndex === lessons.length - 1 ? "إنهاء المسار" : "الدرس التالي ←");

  nextButton.addEventListener("click", () => {
    markCompleted(currentLanguage.id, currentLessonIndex);

    if (currentLessonIndex < lessons.length - 1) {
      currentLessonIndex++;
      renderLessonList();
      renderLesson();
      window.scrollTo({top:0, behavior:"smooth"});
    } else {
      renderLessonList();
      renderLesson();
      alert("أكملت كل دروس هذا المسار. أحسنت! انتقل الآن إلى بناء مشروع صغير.");
    }
  });

  footer.append(completeButton, nextButton);
  lessonContent.appendChild(footer);

  updateCourseProgress();
}

function updateCourseProgress() {
  if (!currentLanguage) return;

  const done = completedFor(currentLanguage.id).length;
  const percent = Math.round(done / lessonCountFor(currentLanguage) * 100);

  document.getElementById("coursePercent").textContent = percent + "%";
  document.getElementById("courseProgressBar").style.width = percent + "%";
}

