function saveProgress() {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(progress));
  } catch {}
}

function completedFor(id) {
  return Array.isArray(progress[id]) ? progress[id] : [];
}

function isCompleted(languageId, lessonIndex) {
  return completedFor(languageId).includes(lessonIndex);
}

function markCompleted(languageId, lessonIndex) {
  const done = completedFor(languageId);

  if (!done.includes(lessonIndex)) {
    done.push(lessonIndex);
    progress[languageId] = done;
    saveProgress();
  }

  updateGlobalStats();
}

