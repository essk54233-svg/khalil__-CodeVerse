const lessonsCache = {};

function buildLessons(language) {
  if (lessonsCache[language.id]) return lessonsCache[language.id];

  const topics = customTopics[language.id] || genericTopics;
  const codes = lessonCode[language.id] || [];

  const existing = topics.map((topic, index) => {
    const sample = codes[index] || ["", "", ""];

    return {
      id: language.id + "-" + index,
      title: topic.title,
      topic,
      code: sample[0],
      output: sample[1],
      note: sample[2],
      theory: false
    };
  });

  /* دمج الدروس التأسيسية (من الصفر) مع الدروس الأصلية */
  const all = typeof composeLessons === "function"
    ? composeLessons(language, existing)
    : existing;

  lessonsCache[language.id] = all;
  return all;
}

function lessonCountFor(language) {
  return buildLessons(language).length;
}

